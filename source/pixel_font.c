static void draw_char(int x, int y, char c, COLOR color, int scale)
{
    unsigned char code = (unsigned char)c;
    if (code >= 'a' && code <= 'z') {
        code -= 'a' - 'A';
    }
    if (code >= 128 || FONT_GLYPHS[code][0] == NULL) {
        return;
    }

    for (int row = 0; row < FONT_GLYPH_HEIGHT; row++) {
        const char *line = FONT_GLYPHS[code][row];
        for (int col = 0; line[col] != '\0'; col++) {
            if (line[col] == '#') {
                int left = x + col * scale;
                int top = y + row * scale;
                m3_rect(left, top, left + scale, top + scale, color);
            }
        }
    }
}

static void draw_text_length(int x, int y, const char *text, int length, COLOR color, int scale)
{
    for (int i = 0; i < length; i++) {
        draw_char(x + i * FONT_CELL_WIDTH * scale, y, text[i], color, scale);
    }
}

void draw_text(int x, int y, const char *text, COLOR color, int scale)
{
    draw_text_length(x, y, text, strlen(text), color, scale);
}

int text_width(const char *text, int scale)
{
    // Leave off the blank column after the last letter so centering looks even
    return (strlen(text) * FONT_CELL_WIDTH - 1) * scale;
}

void draw_text_centered(int y, const char *text, COLOR color, int scale)
{
    draw_text((SCREEN_WIDTH - text_width(text, scale)) / 2, y, text, color, scale);
}

int draw_text_wrapped(int x, int y, const char *text, COLOR color, int max_width)
{
    int max_chars = max_width / FONT_CELL_WIDTH;

    while (*text != '\0') {
        int length = strlen(text);

        if (length > max_chars) {
            // Back up to the last space that fits; if a word is too long, just cut it
            length = max_chars;
            while (length > 0 && text[length] != ' ') {
                length--;
            }
            if (length == 0) {
                length = max_chars;
            }
        }

        draw_text_length(x, y, text, length, color, 1);
        text += length;
        while (*text == ' ') {
            text++;
        }
        y += FONT_LINE_HEIGHT;
    }

    return y;
}
